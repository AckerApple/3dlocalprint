import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";

const rootDir = resolve(".");
const buildDir = resolve(rootDir, ".alert-template-build");
const outputDir = resolve(rootDir, "src/admin/alert-templates");
const outputFile = resolve(outputDir, "alert-template-catalog.ts");

rmSync(buildDir, { recursive: true, force: true });
mkdirSync(buildDir, { recursive: true });

execFileSync(
  resolve(rootDir, "node_modules/.bin/tsc"),
  [
    "firebase-hosting/functions/src/notificationTemplates.ts",
    "--target",
    "ES2022",
    "--module",
    "ES2022",
    "--moduleResolution",
    "Bundler",
    "--skipLibCheck",
    "--declaration",
    "false",
    "--sourceMap",
    "false",
    "--outDir",
    buildDir,
  ],
  { stdio: "inherit" }
);

const compiledUrl = pathToFileURL(resolve(buildDir, "notificationTemplates.js")).href;
const { getAlertTemplateCatalog } = await import(`${compiledUrl}?t=${Date.now()}`);
const catalog = getAlertTemplateCatalog();

mkdirSync(outputDir, { recursive: true });
writeFileSync(
  outputFile,
  [
    "/* Generated by scripts/build-alert-template-catalog.js. Do not edit by hand. */",
    "",
    "export type AlertTemplateCatalogItem = {",
    "  id: string;",
    "  name: string;",
    "  audience: \"internal\" | \"customer\";",
    "  trigger: string;",
    "  sourceFunction: string;",
    "  sampleInput: Record<string, unknown>;",
    "  variables: string[];",
    "  rendered: {",
    "    subject: string;",
    "    text: string;",
    "    html: string;",
    "  };",
    "};",
    "",
    "export const alertTemplateCatalog: AlertTemplateCatalogItem[] = ",
    JSON.stringify(catalog, null, 2),
    ";",
    "",
  ].join("\n"),
  "utf8"
);

rmSync(buildDir, { recursive: true, force: true });
